#!/usr/bin/env bash
# Installs Claude Code from Anthropic's signed apt repository. Runs as root
# at build time.
#   $1  version: "stable" (default, about a week behind and skipping releases
#       with major regressions), "latest", or an exact package version
#       available in the latest channel (apt-cache madison claude-code)
set -euo pipefail

version="${1:-default}"
[[ "$version" == default ]] && version=stable
case "$version" in
  stable|latest) channel="$version"; package=claude-code ;;
  *)             channel=latest;     package="claude-code=${version}" ;;
esac

# Repository signing key, checked against its published fingerprint.
key=/etc/apt/keyrings/claude-code.asc
install -d -m 0755 /etc/apt/keyrings
curl -fsSL https://downloads.claude.ai/keys/claude-code.asc -o "$key"
gpg --show-keys --with-colons "$key" \
  | grep -q '^fpr:::::::::31DDDE24DDFAB679F42D7BD2BAA929FF1A7ECACE:' \
  || { echo "claude-code.asc does not have the expected fingerprint" >&2; exit 1; }

echo "deb [signed-by=${key}] https://downloads.claude.ai/claude-code/apt/${channel} ${channel} main" \
  > /etc/apt/sources.list.d/claude-code.list
apt-get update
apt-get install -y --no-install-recommends "$package"
rm -rf /var/lib/apt/lists/*
claude --version

# Managed instructions directory, regenerated by setup.sh on every start.
install -d -o dev -g "$(id -g dev)" /etc/claude-code
