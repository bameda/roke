#!/usr/bin/env bash
# Prepares the box on every start and runs the coding agent (or the command
# given). The agent-specific part lives in catalog/agents/<agent>/setup.sh.
set -euo pipefail

# roke acp: an editor reads this process's standard output as the protocol, so
# nothing but the agent's adapter may write to it. Everything the box prints
# while preparing, including what mise and the setup scripts print, goes to
# standard error; the real standard output comes back for the final exec.
if [[ "${ROKE_ACP:-0}" == 1 ]]; then
  exec 3>&1 1>&2
fi

log() { printf '[roke] %s\n' "$*" >&2; }
die() { log "ERROR: $*"; exit 1; }

# Per-container scratch space for generated files (not shared with other boxes).
ROKE_RUNTIME=/tmp/roke
mkdir -p "$ROKE_RUNTIME"

# If the image lacks your terminal's terminfo (e.g. xterm-ghostty), fall
# back to a generic one so the TUI renders correctly.
if ! infocmp "${TERM:-dumb}" >/dev/null 2>&1; then
  export TERM=xterm-256color
fi

# Install the tools the project declares (mise.toml, .tool-versions...).
if [[ "${ROKE_MISE_INSTALL:-1}" == "1" ]]; then
  for f in mise.toml .mise.toml mise.local.toml .mise/config.toml .tool-versions; do
    if [[ -f "$f" ]]; then
      log "Installing project tools with mise ($f)..."
      mise install || log "WARNING: 'mise install' failed; continuing anyway."
      break
    fi
  done
fi

# --- MariaDB/MySQL client ------------------------------------------------------
# The mariadb/mysql CLI ignores MYSQL_USER, MYSQL_PASSWORD and MYSQL_DATABASE,
# so write them to ~/.my.cnf (regenerated on every start; removed again in
# projects without the mariadb service).
mycnf="$HOME/.my.cnf"
if [[ -n "${MYSQL_HOST:-}" ]]; then
  (
    umask 077
    cat > "$mycnf" <<MYCNF
# Generated by roke on every start; do not edit.
[client]
host=${MYSQL_HOST}
port=${MYSQL_PORT:-3306}
user=${MYSQL_USER:-}
password=${MYSQL_PASSWORD:-}

[mysql]
database=${MYSQL_DATABASE:-}
MYCNF
  )
elif [[ -f "$mycnf" ]] && head -n1 "$mycnf" | grep -q '^# Generated by roke'; then
  rm -f "$mycnf"
fi

# --- Serena (shared by every agent) -------------------------------------------
SERENA_ENABLED=0
if [[ "${ROKE_SERENA:-0}" == "1" ]]; then
  if command -v serena >/dev/null 2>&1; then
    SERENA_ENABLED=1
  else
    log "WARNING: ROKE_SERENA=1 but the image was built without Serena (INSTALL_SERENA=0)."
  fi
fi

if ((SERENA_ENABLED)); then
  cfg="$SERENA_HOME/serena_config.yml"
  if [[ ! -f "$cfg" ]]; then
    mkdir -p "$SERENA_HOME"
    cp /opt/serena/serena_config.base.yml "$cfg"
  fi
  # There is no browser inside the box: the dashboard only makes sense when
  # its port is published (ROKE_SERENA_DASHBOARD=1, handled by bin/roke).
  if [[ "${ROKE_SERENA_DASHBOARD:-0}" == "1" ]]; then
    dash=True; listen=0.0.0.0
  else
    dash=False; listen=127.0.0.1
  fi
  sed -i -E \
    -e "s/^web_dashboard:.*/web_dashboard: ${dash}/" \
    -e 's/^web_dashboard_open_on_launch:.*/web_dashboard_open_on_launch: False/' \
    -e "s/^web_dashboard_listen_address:.*/web_dashboard_listen_address: ${listen}/" \
    "$cfg"
  log "Serena enabled for $PWD"
fi

# --- Helpers for catalog/agents/<agent>/setup.sh --------------------------------------

# serena_command CONTEXT: sets SERENA_CMD to the command that starts Serena's
# MCP server for the current project, with the given Serena context.
serena_command() {
  # Serena's usage statistics are off unless ROKE_SERENA_USAGE_REPORTING=1.
  # They go in the command itself: not every agent passes the environment
  # on to the MCP servers it starts.
  local reporting=false
  [[ "${ROKE_SERENA_USAGE_REPORTING:-0}" == 1 ]] && reporting=true
  # shellcheck disable=SC2034  # read by the agent's setup.sh
  SERENA_CMD=(env "SERENA_USAGE_REPORTING=$reporting"
              serena start-mcp-server --context "$1" --project "$PWD"
              --open-web-dashboard false)
}

# roke_link_config SRC DEST: links every entry of SRC (your read-only agent
# configuration) into DEST, removing links left from previous starts. DEST
# stays writable, so the agent can still create its own files there.
roke_link_config() {
  local src="$1" dest="$2" entry name
  mkdir -p "$dest"
  find "$dest" -maxdepth 1 -type l -lname "$src/*" -delete
  [[ -d "$src" ]] || return 0
  for entry in "$src"/* "$src"/.[!.]*; do
    [[ -e "$entry" ]] || continue
    name="$(basename "$entry")"
    # AGENTS.md is added to the combined instructions instead (see below).
    case "$name" in .git|.gitignore|README.md|AGENTS.md) continue ;; esac
    if [[ -e "$dest/$name" && ! -L "$dest/$name" ]]; then
      log "WARNING: $dest/$name exists in the project's home volume and hides yours; remove it with roke shell."
      continue
    fi
    ln -sfn "$entry" "$dest/$name"
  done
}

# --- Agent ----------------------------------------------------------------------
agent="${ROKE_AGENT:-}"
[[ -n "$agent" ]] || die "no agent selected (ROKE_AGENT); start the box with bin/roke"
agent_dir="/opt/roke/agents/$agent"
[[ -f "$agent_dir/setup.sh" ]] || die "unknown agent: $agent"
grep -qxF "$agent" /etc/roke/installed-agents \
  || die "the agent '$agent' is not installed in the image: add it to ROKE_AGENTS and run roke build"

# The agent's instructions: the box's common ones, the agent's own, then
# yours (for every agent, then for this agent only) and the project's
# private ones, if any.
AGENT_INSTRUCTIONS="$ROKE_RUNTIME/instructions.md"
{
  cat /opt/roke/agents/AGENTS.md
  for extra in "$agent_dir/AGENTS.md" /run/roke/user-AGENTS.md \
               /run/roke/agent-config/AGENTS.md /run/roke/project-AGENTS.md; do
    if [[ -f "$extra" ]]; then
      printf '\n'
      cat "$extra"
    fi
  done
} > "$AGENT_INSTRUCTIONS"

# shellcheck disable=SC2034  # read by the agent's setup.sh
AGENT_CONFIG=/run/roke/agent-config
AGENT_COMMAND=()
AGENT_ARGS=()
AGENT_CONTINUE=()
ACP_COMMAND=()
# shellcheck source=/dev/null
source "$agent_dir/setup.sh"
((${#AGENT_COMMAND[@]})) || die "catalog/agents/$agent/setup.sh did not set AGENT_COMMAND"

# roke acp: run the agent's Agent Client Protocol adapter, which the editor
# talks to, instead of the agent.
if [[ "${ROKE_ACP:-0}" == 1 ]]; then
  ((${#ACP_COMMAND[@]})) \
    || die "catalog/agents/$agent does not support the Agent Client Protocol (ACP_COMMAND in its setup.sh)"
  (($# == 0)) || die "roke acp takes no command"
  set -- "${ACP_COMMAND[@]}"
# No command: run the agent. When the agent is run explicitly (for example
# "roke exec claude --print ..."), its extra arguments are added too.
# With ROKE_CONTINUE=1 (roke continue), resume the last session instead.
elif (($# == 0)); then
  set -- "${AGENT_COMMAND[@]}"
  if [[ "${ROKE_CONTINUE:-0}" == "1" ]]; then
    ((${#AGENT_CONTINUE[@]})) \
      || die "catalog/agents/$agent does not say how to resume a session (AGENT_CONTINUE in its setup.sh)"
    set -- "$@" "${AGENT_CONTINUE[@]}"
  fi
fi
if ((${#AGENT_ARGS[@]})) && [[ "$1" == "${AGENT_COMMAND[0]}" ]]; then
  shift
  set -- "${AGENT_COMMAND[0]}" "${AGENT_ARGS[@]}" "$@"
fi

if [[ "${ROKE_ACP:-0}" == 1 ]]; then
  exec 1>&3 3>&-
fi
exec "$@"
