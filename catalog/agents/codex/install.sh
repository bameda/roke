#!/usr/bin/env bash
# Installs Codex CLI (npm package @openai/codex) in the image. Runs as root at
# build time.
#   $1  version: an npm version or tag, or "default" (latest)
set -euo pipefail

version="${1:-default}"
[[ "$version" == default ]] && version=latest

# The npm package ships Codex's native binary for the platform.
npm install -g "@openai/codex@${version}"
codex --version
npm cache clean --force

# The adapter editors talk to through roke acp (Agent Client Protocol).
# renovate: datasource=npm depName=@agentclientprotocol/codex-acp
ACP_ADAPTER_VERSION=2.6.0
"$(dirname "$0")/../install-acp.sh" \
  @agentclientprotocol/codex-acp "$ACP_ADAPTER_VERSION" codex-acp

# System configuration directory, regenerated by setup.sh on every start.
install -d -o dev -g "$(id -g dev)" /etc/codex
